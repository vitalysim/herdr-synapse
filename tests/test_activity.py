class WatchFileTests(unittest.TestCase):
    def setUp(self) -> None:
        self.ts = TempState()
        self.addCleanup(self.ts.cleanup)
        self.session = self.ts.session

    def test_add_remove_and_refresh(self):
        self.assertEqual(A.watched(self.session), [])
        entry = A.add_watch(self.session, {"terminal_id": "term_a", "pane_id": "w1:p1", "name": "a", "kind": "claude", "team": None}, "human")
        self.assertEqual((entry["by"], entry["terminal_id"]), ("human", "term_a"))
        self.assertTrue(entry["at"])
        doc = store.read_json(A.watch_path(self.session))
        self.assertEqual(doc["v"], 1)
        self.assertEqual(oct(os.stat(A.watch_path(self.session)).st_mode & 0o777), "0o600")
        again = A.add_watch(self.session, {"terminal_id": "term_a", "pane_id": "w9:p1", "team": "alpha"}, "someone-else")
        self.assertEqual((again["pane_id"], again["team"], again["name"], again["by"], again["at"]), ("w9:p1", "alpha", "a", "human", entry["at"]))
        self.assertTrue(A.is_watched(self.session, "term_a"))
        self.assertEqual(A.remove_watch(self.session, "term_a")["terminal_id"], "term_a")
        self.assertIsNone(A.remove_watch(self.session, "term_a"))
        self.assertFalse(A.is_watched(self.session, "term_a"))

    def test_the_limit(self):
        for i in range(A.MAX_WATCHED):
            A.add_watch(self.session, {"terminal_id": "term_{}".format(i)}, "human")
        with self.assertRaises(HerdrTeamError) as ctx:
            A.add_watch(self.session, {"terminal_id": "term_over"}, "human")
        self.assertEqual((ctx.exception.code, ctx.exception.details["max"]), ("watch_limit", 20))
        A.add_watch(self.session, {"terminal_id": "term_3", "pane_id": "w1:p3"}, "human")  # re-flagging is not an addition

    def test_bad_rows_and_ids_are_dropped(self):
        store.write_json(A.watch_path(self.session), {"v": 1, "agents": [
            {"terminal_id": "../escape"}, {"terminal_id": "term_ok", "name": 5}, "junk", {"terminal_id": "term_ok"}, {}]})
        self.assertEqual([e["terminal_id"] for e in A.watched(self.session)], ["term_ok"])
        with self.assertRaises(HerdrTeamError):
            A.add_watch(self.session, {"terminal_id": "bad/id"}, "human")
        store.write_json(A.watch_path(self.session), ["not", "a", "doc"])
        self.assertEqual(A.watched(self.session), [])

    def test_sync_follows_a_moved_pane_and_writes_only_on_change(self):
        A.add_watch(self.session, {"terminal_id": "term_a", "pane_id": "w1:p1", "name": "a", "kind": "claude"}, "human")
        self.assertFalse(A.sync_watch(self.session, {"term_a": {"pane_id": "w1:p1", "name": "a", "agent": "claude"}}))
        self.assertTrue(A.sync_watch(self.session, {"term_a": {"pane_id": "w4:p2", "name": "a2", "agent": "claude"}}))
        self.assertEqual((A.watched(self.session)[0]["pane_id"], A.watched(self.session)[0]["name"]), ("w4:p2", "a2"))

    def test_the_cache_goes_with_the_flag_and_old_ones_are_pruned(self):
        path = A.cache_path(self.session, "term_a")
        store.write_json(path, {"v": 1})
        A.add_watch(self.session, {"terminal_id": "term_a"}, "human")
        A.remove_watch(self.session, "term_a")
        self.assertFalse(path.exists())
        stale, kept, fresh = (A.cache_path(self.session, t) for t in ("term_old", "term_keep", "term_new"))
        for p in (stale, kept, fresh):
            store.write_json(p, {"v": 1})
        old = time.time() - 2 * A.CACHE_MAX_AGE_S
        os.utime(stale, (old, old))
        os.utime(kept, (old, old))
        self.assertEqual(A.prune_cache(self.session, {"term_keep"}), 1)
        self.assertEqual((stale.exists(), kept.exists(), fresh.exists()), (False, True, True))
        self.assertIsNone(A.cache_path(self.session, "../x"))

    def test_clear_doing_tokens_clears_stored_and_moved_panes(self):
        A.add_watch(self.session, {"terminal_id": "term_a", "pane_id": "w1:p1"}, "human")
        A.add_watch(self.session, {"terminal_id": "term_b", "pane_id": "w1:p2"}, "human")
        api = FakeApi()
        api.set_response("agent.list", {"type": "agent_list", "agents": [fake_agent("w5:p5", "term_a", "claude", None)]})
        self.assertEqual(A.clear_doing_tokens(self.ts.layout, api), 3)
        cleared = [p for m, p in api.calls if m == "pane.report_metadata"]
        self.assertEqual(sorted(p["pane_id"] for p in cleared), ["w1:p1", "w1:p2", "w5:p5"])
        self.assertTrue(all(p["tokens"] == {"team_doing": None} and p["source"] == "herdr-synapse:watch" for p in cleared))
        api.set_error("pane.report_metadata", "server_not_running", "down")
        self.assertEqual(A.clear_doing_tokens(self.ts.layout, api), 0)
        for entry in A.watched(self.session):
            A.remove_watch(self.session, entry["terminal_id"])
        self.assertEqual(A.clear_doing_tokens(self.ts.layout, FakeApi()), 0)


