def iso(epoch: float) -> str:
    return transcripts.iso_of(epoch)


def session(kind: str, value: str, ref: str = "id") -> Dict[str, Any]:
    return {"source": "herdr:" + kind, "agent": kind, "kind": ref, "value": value}


def write_jsonl(path: Path, records: List[Any], tail: str = "") -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [r if isinstance(r, str) else json.dumps(r) for r in records]
    path.write_text("\n".join(lines) + "\n" + tail, encoding="utf-8")
    return path


def append_jsonl(path: Path, records: List[Any], tail: str = "") -> None:
    with path.open("a", encoding="utf-8") as handle:
        for record in records:
            handle.write((record if isinstance(record, str) else json.dumps(record)) + "\n")
        handle.write(tail)


