class DescribeToolTests(unittest.TestCase):
    def test_each_tool_is_its_name_or_one_short_argument(self):
        cases = [
            (("Bash", {"command": "python pull.py\necho done"}), ("run", "python pull.py", [])),
            (("shell", {"command": ["bash", "-lc", "rg -n retry src/"]}), ("run", "rg -n retry src/", [])),
            (("shell", {"command": ["git", "status", "--short"]}), ("run", "git status --short", [])),
            (("exec_command", {"cmd": "pytest -q"}), ("run", "pytest -q", [])),
            (("Edit", {"file_path": "src/a.py", "old_string": "x", "new_string": "BODY"}), ("edit", "src/a.py", ["src/a.py"])),
            (("write", {"filePath": "/w/b.go", "content": "BODY"}), ("edit", "/w/b.go", ["/w/b.go"])),
            (("apply_patch", {"input": PATCH}), ("edit", "src/retry.py +1", ["src/retry.py", "tests/test_retry.py"])),
            (("Read", {"file_path": "data/README.md"}), ("read", "data/README.md", [])),
            (("Grep", {"pattern": "churn", "path": "src/"}), ("search", '"churn" in src/', [])),
            (("Glob", {"pattern": "**/*.py"}), ("search", '"**/*.py"', [])),
            (("WebFetch", {"url": "https://user:secret@docs.example.test/x?y=1", "prompt": "p"}), ("web", "docs.example.test", [])),
            (("WebSearch", {"query": "backoff jitter"}), ("web", "backoff jitter", [])),
            (("Task", {"subagent_type": "Explore", "description": "find it", "prompt": "LONG"}), ("agent", "Explore find it", [])),
            (("mcp__synapse_canvas__look", {"region": "x"}), ("mcp", "synapse_canvas look", [])),
            (("SomethingNew", {"secret_arg": "value"}), ("tool", "SomethingNew", [])),
        ]
        for (name, args), expected in cases:
            self.assertEqual(A.describe_tool(name, args), expected, name)

    def test_a_patch_typed_through_the_shell_is_an_edit(self):
        heredoc = "apply_patch <<'EOF'\n" + PATCH + "EOF"
        self.assertEqual(A.describe_tool("shell", {"command": ["bash", "-lc", heredoc]}), ("edit", "src/retry.py +1", ["src/retry.py", "tests/test_retry.py"]))
        self.assertEqual(A.describe_tool("shell", {"command": ["apply_patch", PATCH]})[0], "edit")

    def test_odd_arguments_never_raise(self):
        for args in (None, "a string", 3, [], {"command": 7}, {"file_path": ["x"]}, {"url": 5}):
            icon, text, files = A.describe_tool("Bash", args) or ("", "", [])
            self.assertTrue(text)
            A.describe_tool("Edit", args)
            A.describe_tool("WebFetch", args)
        self.assertIsNone(A.describe_tool("", {}))
        self.assertIsNone(A.describe_tool(None, {}))

    def test_arguments_are_redacted_and_clipped(self):
        icon, text, _ = A.describe_tool("Bash", {"command": "curl -H 'Authorization: Bearer {}' https://x".format("t" * 40)})
        self.assertIn("[redacted:bearer_token]", text)
        icon, text, _ = A.describe_tool("Bash", {"command": "export GITHUB_TOKEN={}".format(GITHUB_TOKEN)})
        self.assertNotIn(GITHUB_TOKEN, text)
        self.assertIn("[redacted:", text)
        icon, text, _ = A.describe_tool("Bash", {"command": "echo " + "y" * 500})
        self.assertLessEqual(len(text), A.ACTION_CHARS)
        self.assertTrue(text.endswith("…"))
        icon, text, _ = A.describe_tool("Bash", {"command": "printf '\x1b[31mred\x1b[0m'\ttab"})
        self.assertNotIn("\x1b", text)

    def test_redact_covers_the_board_and_the_stricter_shapes(self):
        text = A.redact("keys {} {} {} and -----BEGIN RSA PRIVATE KEY-----\nabc\n-----END RSA PRIVATE KEY----- done".format(ANTHROPIC_KEY, AWS_KEY, "sk-" + "q" * 17))
        for secret in (ANTHROPIC_KEY, AWS_KEY, "sk-" + "q" * 17, "abc"):
            self.assertNotIn(secret, text)
        self.assertIn("[redacted:anthropic_key]", text)
        self.assertIn("[redacted:private_key]", text)


class PlanTests(unittest.TestCase):
    def test_steps_and_the_current_one(self):
        steps = A.todo_steps([{"content": "a", "status": "completed"}, {"step": "b", "status": "in_progress"}, {"subject": "c", "status": "weird"},
                              "not a dict", {"status": "pending"}])
        self.assertEqual(steps, [{"text": "a", "status": "completed"}, {"text": "b", "status": "in_progress"}, {"text": "c", "status": "pending"}])
        plan = A.make_plan(steps, "todo")
        self.assertEqual((plan["current"], plan["total"], plan["source"]), (2, 3, "todo"))
        self.assertIsNone(A.make_plan([], "todo"))
        self.assertIsNone(A.make_plan([{"text": "a", "status": "completed"}], "todo")["current"])
        self.assertEqual(A.todo_steps([{"content": "x", "status": "Done"}, {"content": "y", "status": "in progress"}])[0]["status"], "completed")
        self.assertEqual(A.todo_steps([{"content": "y", "status": "in progress"}])[0]["status"], "in_progress")

    def test_a_long_plan_is_capped_but_counted(self):
        plan = A.make_plan([{"text": str(i), "status": "pending"} for i in range(80)], "update_plan")
        self.assertEqual((len(plan["steps"]), plan["total"]), (A.MAX_PLAN_STEPS, 80))


